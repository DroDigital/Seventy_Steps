"""Round 125, a baked plant into the game's data (render/floraKit.ts decodes it): `src/data/flora/floraIndex.ts` (each model's height, trunk,
first fork and crown) and `floraPack.ts` (each model's bytes, base64). A model's blob, little endian:

  uint16 version (1), uint16 wood points, uint16 wood faces, uint16 leaf points, uint16 leaf faces, uint16 cards;
  float32 box (lo xyz, hi xyz), float32 a card's longest half-axis;
  wood points: int16 xyz within the box, int8 normal xyz, uint8 light (the baked AO), uint8 slot, uint16 uv (x 256: metres round and
    along its bark), uint8 reach (x 255), uint8 phase (x 255);  then uint16 faces;
  leaf points (solid leaf meshes: a fungus's caps): as the wood's, its uv the atlas's (x 65535 / 2), then uint8 flutter; then faces;
  cards: int16 centre xyz within the box, int8 u xyz and v xyz (x the longest half-axis / 127), uint8 cell (and 16 if it hangs),
    uint8 slot, uint8 light at its four corners (foot left, foot right, head right, head left), int8 normal xyz, uint8 reach, uint8 phase,
    uint8 v0, uint8 v1 (the share of its cell it shows, for a frond in two cards).
"""
import base64
import os
import struct

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, '..', '..', 'src', 'data', 'flora')


def q16(x, lo, hi):
    return max(-32768, min(32767, int(round((x - lo) / max(hi - lo, 1e-6) * 65535 - 32768))))


def s8(x):
    return max(-127, min(127, int(round(x * 127))))


def u8(x):
    return max(0, min(255, int(round(x * 255))))


def blob(wood, leaf, cards):
    pts = list(wood.pos) + (list(leaf.pos) if leaf else []) + [q for c in cards for q in c.corners()]
    lo = [min(p[i] for p in pts) for i in range(3)]
    hi = [max(p[i] for p in pts) for i in range(3)]
    half = max([max(c.u.length, c.v.length) for c in cards] + [0.01])
    out = bytearray(struct.pack('<6H', 1, len(wood.pos), len(wood.tris), len(leaf.pos) if leaf else 0, len(leaf.tris) if leaf else 0, len(cards)))
    out += struct.pack('<7f', *lo, *hi, half)

    def points(m, atlas):
        for i, p in enumerate(m.pos):
            n = m.normal[i]
            u, v = m.uv[i]
            uv = (u / 2 * 65535, v / 2 * 65535) if atlas else (u * 256, v * 256)
            out.extend(struct.pack('<3h3bBBHHBB', *(q16(p[k], lo[k], hi[k]) for k in range(3)), s8(n.x), s8(n.y), s8(n.z), u8(m.ao[i]), m.slot[i], max(0, min(65535, int(round(uv[0])))), max(0, min(65535, int(round(uv[1])))), u8(min(1.0, m.reach[i])), u8(m.phase[i] % 1.0)))
            if atlas:
                out.extend(struct.pack('<B', u8(min(1.0, m.flutter[i]))))
        for t in m.tris:
            out.extend(struct.pack('<3H', *t))

    points(wood, False)
    if leaf:
        points(leaf, True)
    for c in cards:
        out += struct.pack('<3h', *(q16(c.center[k], lo[k], hi[k]) for k in range(3)))
        out += struct.pack('<6b', *(s8(c.u[k] / half) for k in range(3)), *(s8(c.v[k] / half) for k in range(3)))
        out += struct.pack('<BB4B3bBBBB', c.cell | (16 if c.hang else 0), c.slot, *(u8(a) for a in c.ao), s8(c.normal.x), s8(c.normal.y), s8(c.normal.z), u8(min(1.0, c.reach)), u8(c.phase % 1.0), u8(c.v0), u8(c.v1))
    return bytes(out)


def write(models, index):
    """models: {id: bytes}; index: {id: dict of numbers}. Writes the two modules."""
    os.makedirs(OUT, exist_ok=True)
    head = '/** Generated by tools/flora/build.py (docs/FLORA.md): do not edit by hand. */\n\n'
    with open(os.path.join(OUT, 'floraPack.ts'), 'w') as f:
        f.write(head + 'export const FLORA_PACK: Readonly<Record<string, string>> = {\n')
        for k in sorted(models):
            f.write(f"  '{k}': '{base64.b64encode(models[k]).decode()}',\n")
        f.write('};\n')
    with open(os.path.join(OUT, 'floraIndex.ts'), 'w') as f:
        f.write(head + '/** A model: its height, its trunk\'s radius a metre up, the height of its first fork, its crown (centre xyz, half-extents xyz), its faces. */\n')
        f.write('export interface FloraInfo {\n  h: number;\n  r: number;\n  fork: number;\n  crown: readonly [number, number, number, number, number, number];\n  faces: number;\n}\n\n')
        f.write('export const FLORA_INDEX: Readonly<Record<string, FloraInfo>> = {\n')
        for k in sorted(index):
            i = index[k]
            crown = ', '.join(f'{x:.2f}' for x in i['crown'])
            f.write(f"  '{k}': {{ h: {i['h']:.2f}, r: {i['r']:.3f}, fork: {i['fork']:.2f}, crown: [{crown}], faces: {i['faces']} }},\n")
        f.write('};\n')
