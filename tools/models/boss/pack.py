"""Fits a model's triangles to the game and writes them in its compact form (the baker, tools/models/bake_boss_models.py): turned to face +z,
scaled to the metres asked, its footprint centred and its foot on the ground, welded and held as 16-bit points within its own box, each
face with a material class and the colour under it. The blob is the one src/render/modelKit.ts decodes (the Kenney models' own form):
uint16 points and faces, six float32 box, int16 points, uint16 face indices, then four bytes a face: class (bit 7: drawn both sides), r, g, b."""
import struct
import numpy as np

DOUBLE = 0x80

def rotate_y(t, deg):
    """Turns triangles about the vertical, counter-clockwise seen from above in the game's frame (x right, z front): +deg turns +x toward -z."""
    if not deg:
        return t
    a = np.radians(deg)
    c, s = np.cos(a), np.sin(a)
    x, z = t[..., 0].copy(), t[..., 2].copy()
    out = t.copy()
    out[..., 0] = x * c + z * s
    out[..., 2] = -x * s + z * c
    return out

def tip(t, rx=0, rz=0):
    """Tips triangles about x (y toward z) and then about z (x toward y), degrees."""
    if rx:
        a = np.radians(rx); c, s_ = np.cos(a), np.sin(a)
        y, z = t[..., 1].copy(), t[..., 2].copy()
        t = t.copy(); t[..., 1] = y * c - z * s_; t[..., 2] = y * s_ + z * c
    if rz:
        a = np.radians(rz); c, s_ = np.cos(a), np.sin(a)
        x, y = t[..., 0].copy(), t[..., 1].copy()
        t = t.copy(); t[..., 0] = x * c - y * s_; t[..., 1] = x * s_ + y * c
    return t

def fitted(t, fit, squash=(1, 1, 1), centre=True, ground=True):
    """`fit`: {'scale': k} | {'height': m} | {'length': m} (the longer side along the ground) | {'width': m} (x) | {'depth': m} (z)."""
    p = t.reshape(-1, 3)
    ext = p.max(axis=0) - p.min(axis=0)
    if 'scale' in fit:
        k = fit['scale']
    elif 'height' in fit:
        k = fit['height'] / max(ext[1], 1e-6)
    elif 'length' in fit:
        k = fit['length'] / max(ext[0], ext[2], 1e-6)
    elif 'width' in fit:
        k = fit['width'] / max(ext[0], 1e-6)
    elif 'depth' in fit:
        k = fit['depth'] / max(ext[2], 1e-6)
    else:
        k = 1.0
    t = t * np.array([k * squash[0], k * squash[1], k * squash[2]])
    p = t.reshape(-1, 3)
    lo, hi = p.min(axis=0), p.max(axis=0)
    shift = np.array([(lo[0] + hi[0]) / 2 if centre else 0, lo[1] if ground else 0, (lo[2] + hi[2]) / 2 if centre else 0])
    return t - shift, shift, k

def bake(t, col, cls, double=()):
    """(blob, lo, hi, points, faces) of triangles t (n,3,3), colours (n,3) 0..1, classes (n,)."""
    pts = t.reshape(-1, 3)
    lo, hi = pts.min(axis=0), pts.max(axis=0)
    span = np.maximum(hi - lo, 1e-6)
    q = np.round((pts - lo) / span * 65535 - 32768).astype(np.int32)
    uniq, inv = np.unique(q, axis=0, return_inverse=True)
    inv = inv.reshape(-1, 3)
    keep = (inv[:, 0] != inv[:, 1]) & (inv[:, 1] != inv[:, 2]) & (inv[:, 0] != inv[:, 2])
    inv, col, cls = inv[keep], col[keep], cls[keep]
    if len(uniq) > 65535 or len(inv) > 65535:
        raise ValueError(f'{len(uniq)} points, {len(inv)} faces: over the 16-bit limit; decimate or split it')
    blob = bytearray(struct.pack('<HH', len(uniq), len(inv)))
    blob += struct.pack('<6f', *lo, *hi)
    blob += uniq.astype('<i2').tobytes()
    blob += inv.astype('<u2').tobytes()
    flags = cls.astype(np.uint8) | np.where(np.isin(cls, list(double)), DOUBLE, 0).astype(np.uint8)
    rows = np.zeros((len(inv), 4), dtype=np.uint8)
    rows[:, 0] = flags
    rows[:, 1:] = np.round(np.clip(col, 0, 1) * 255).astype(np.uint8)
    blob += rows.tobytes()
    return bytes(blob), lo, hi, len(uniq), len(inv)

SETS = {  # the baked files: the name of each, and what its models are
    'boss': ('BOSS', "The boss places' models", "The boss places' models' triangles"),
    'gate': ('GATE', "The arenas' gates' models, hung by data/gateStyles.ts", "The arenas' gates' triangles"),
    'web': ('WEB', "The models taken from free web sources for the arenas', halls' and gates' sets (manifest_web.py)", "The web-sourced models' triangles"),
}

def ts_index(entries, kind='boss'):
    """src/data/models/<kind>Index.ts: each model's box, kit, round, triangles, solids and anchors."""
    name, what, _ = SETS[kind]
    out = [f"/** {what} (generated by tools/models/bake_boss_models.py from the packs in tools/models/boss/manifest*.py; their licences and what was changed: CREDITS.md): each one's box in its own units (metres, footprint centred, foot on the ground), the pack it comes from, whether its footprint is round, what a body cannot walk through (`solids`: cx, cz, half x, half z, from y, to y) and where a flame or a light sits (`anchors`). Data only. */\n\n",
           "import type { ModelInfo } from './index';\n\n",
           f"export const {name}_INFO: Readonly<Record<string, ModelInfo>> = {{\n"]
    for k, v in entries.items():
        box = ', '.join(f"{a}: {v[a]}" for a in ('x0', 'x1', 'y0', 'y1', 'z0', 'z1'))
        extra = ''
        extra += ', solids: ' + str(v.get('solids', [])).replace(' ', '')  # (always: none is []: a model with no solids is walked through, not boxed)
        if v.get('anchors'):
            extra += ', anchors: ' + str(v['anchors']).replace(' ', '')
        out.append("  %s: { kit: '%s', %s, round: %s, tris: %d%s },\n" % (k, v['kit'], box, 'true' if v['round'] else 'false', v['tris'], extra))
    out.append('};\n')
    return ''.join(out)

def ts_pack(blobs, kind='boss'):
    name, _, what = SETS[kind]
    out = [f"/** {what} (generated by tools/models/bake_boss_models.py; read by render/modelKit.ts): base64 of each model's bytes: its point and face counts, its box, its points as 16-bit values within it, its faces as indices, and each face's material class (bit 7: drawn both sides) and colour. Data only. */\n\n",
           f"export const {name}_PACK: Readonly<Record<string, string>> = {{\n"]
    for k, v in blobs.items():
        out.append(f"  {k}: '{v}',\n")
    out.append('};\n')
    return ''.join(out)
