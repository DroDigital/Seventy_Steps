"""Bakes the Actions on the investigator's rig (animate.py) into the game's data, `src/data/player/playerClips.ts`: for each clip, the pelvis's position and every joint's
rotation on every 60 Hz frame, read back from Blender's evaluation of the rig (so what the game plays is what Blender shows), as one little-endian blob:

    uint16 samples, uint8 flags (1: a loop), uint8 moving joints; uint8 index (in frame.py's ORDER) of each moving joint; int16 x 4 rotation of every joint (the still ones' values:
    the moving ones' are here too, and are overridden by their tracks); int16 x 3 pelvis (millimetres from its rest, the whole track, or none when it stays at rest, flag 2);
    then int16 x 4 for each moving joint on each sample (a quaternion x 32767, one hemisphere along time).

Called by bake_player.py after the parts are baked; `python3 -I tools/player/clipbake.py` alone bakes the clips from the .blend as it stands.
"""
import os, sys, json, base64, struct
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import bpy
import numpy as np
import frame as F
import rigmath as RM

OUT = os.path.join(HERE, '..', '..', 'src', 'data', 'player')
Q = 32767.0
STILL = 2e-4  # a joint whose rotation never changes by more than this (radians-ish) keeps one value


def evaluate(rig, act, rest, n):
    rig.animation_data.action = act
    rig.animation_data.action_slot = act.slots[0]
    quats = {j: np.zeros((n, 4)) for j in F.ORDER}
    body = np.zeros((n, 3))
    for i in range(n):
        bpy.context.scene.frame_set(i)
        pose = RM.pose_from_matrices({b.name: np.array(b.matrix) for b in rig.pose.bones}, rest)
        for j in F.ORDER:
            q = pose[j] / np.linalg.norm(pose[j])
            if i and np.dot(q, quats[j][i - 1]) < 0:
                q = -q
            quats[j][i] = q
        body[i] = pose['body_pos']
    return quats, body


def blob(quats, body, loop):
    n = len(body)
    moving = [j for j in F.ORDER if np.abs(quats[j] - quats[j][0]).max() > STILL]
    rest_body = np.array(F.JOINTS['body'][1], float)
    pelvis_moves = np.abs(body - rest_body).max() > 5e-4
    b = bytearray(struct.pack('<HBB', n, (1 if loop else 0) | (2 if not pelvis_moves else 0), len(moving)))
    b += bytes(F.ORDER.index(j) for j in moving)
    for j in F.ORDER:
        b += np.round(quats[j][0] * Q).astype('<i2').tobytes()
    if pelvis_moves:
        b += np.round((body - rest_body) * 1000).astype('<i2').tobytes()
    for j in moving:
        b += np.round(quats[j] * Q).astype('<i2').tobytes()
    return base64.b64encode(bytes(b)).decode(), len(moving)


def bake(out=OUT, blend=None):
    if blend:
        bpy.ops.wm.open_mainfile(filepath=blend)
    rig = bpy.data.objects['Investigator_Rig']
    rig.animation_data_create()
    rest = {b.name: np.array(b.matrix_local) for b in rig.data.bones}
    acts = sorted((a for a in bpy.data.actions if 'game_frames' in a), key=lambda a: a.name)
    lines, total = [], 0
    for act in acts:
        loop = bool(act['game_loop'])
        frames = int(act['game_frames'])
        n = frames if loop else frames + 1
        quats, body = evaluate(rig, act, rest, n)
        text, moving = blob(quats, body, loop)
        total += len(text)
        marks = json.loads(act['game_markers'])
        flags = []
        if act.get('game_drawn'):
            flags.append('drawn: true')
        props = json.loads(act.get('game_props', '[]'))
        if props:
            flags.append('props: [' + ', '.join(f"'{p}'" for p in props) + ']')
        lines.append(f"  '{act.name}': {{ frames: {frames}, loop: {'true' if loop else 'false'}, marks: {json.dumps(marks)}, {', '.join(flags) + ', ' if flags else ''}data: '{text}' }},")
    rig.animation_data.action = None
    head = '/** Generated by tools/player/clipbake.py from the Actions in tools/player/build/investigator.blend (docs/PLAYER.md): do not edit by hand. */\n'
    open(os.path.join(out, 'playerClips.ts'), 'w').write(
        head + "\nexport interface PlayerClipData {\n  frames: number; // the move's length in 60 Hz frames (a loop's period)\n  loop: boolean;\n  marks: Readonly<Record<string, number>>; // the frames of hit0, hit1, item, shot, volley, parry0, parry1: what the game's own data puts there\n"
        "  drawn?: boolean; // the sword-cane's blade is drawn for it\n  props?: readonly string[]; // what the off-hand holds (the groups of the figure shown: flask, laudanum, syringe, powder, match, book)\n  data: string; // playerClips.ts's blob, see tools/player/clipbake.py\n}\n"
        "\nexport const PLAYER_CLIPS: Readonly<Record<string, PlayerClipData>> = {\n" + '\n'.join(lines) + '\n};\n')
    print(f'baked {len(acts)} clips, {total // 1024} KB of data')


if __name__ == '__main__':
    a = sys.argv[1:]
    bake(OUT, a[a.index('--blend') + 1] if '--blend' in a else os.path.join(HERE, 'build', 'investigator.blend'))
