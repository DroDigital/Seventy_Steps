#!/usr/bin/env python3
"""Bakes the investigator from his .blend into the game's data: `src/data/player/playerIndex.ts` (each part: its joint, texture, group, glow and place) and
`playerPack.ts` (each part's triangles, in the compact form below), and, with the clips keyed on his rig, `playerClips.ts` (clips.py). Run after
build_blend.py (or after editing the .blend in Blender):

    python3 -I tools/player/bake_player.py [--blend f.blend] [--no-clips]          (needs `pip install bpy numpy`)  then  npm run check

A part's blob (little endian): uint16 points, uint16 faces, uint16 colours; float32 box (lo xyz, hi xyz); int16 points within the box; uint16 face indices;
uint8 colour index per face; float32 colours (r, g, b) as the game draws them (the .blend keeps half of them: COLOUR_GAIN). Points are in the joint's own
frame (game axes) and welded; the game draws every face flat.
"""
import base64, os, struct, sys, json
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import bpy
import numpy as np
import frame as F

OUT = os.path.join(HERE, '..', '..', 'src', 'data', 'player')
COLOUR_GAIN = 2.0


def mesh_parts(obj):
    """[(name, joint, group, tex, glow, at, verts (game axes, joint frame), faces, face colours)] of an object: one entry for a prop, one for each joint a body mesh is skinned to."""
    mesh = obj.data
    n = len(mesh.vertices)
    co = np.empty(n * 3)
    mesh.vertices.foreach_get('co', co)
    co = F.from_blender(co.reshape(-1, 3))
    names = {vg.index: vg.name for vg in obj.vertex_groups}
    joint_of = [names[max(v.groups, key=lambda g: g.weight).group] for v in mesh.vertices]
    tri = np.array([p.vertices[:] for p in mesh.polygons], int)
    if tri.shape[1] != 3:
        raise ValueError(f'{obj.name}: faces must be triangles')
    corner = mesh.color_attributes['Col']
    col = np.empty(len(corner.data) * 4)
    corner.data.foreach_get('color', col)
    col = col.reshape(-1, 4)[:, :3].reshape(-1, 3, 3)[:, 0] * COLOUR_GAIN  # a colour for each face: its first corner's
    out = []
    joints = sorted(set(joint_of), key=F.ORDER.index)
    for j in joints:
        fi = np.array([i for i, t in enumerate(tri) if all(joint_of[v] == j for v in t)], int)
        if not len(fi):
            continue
        at = np.array(list(obj['game_at']), float) if 'game_at' in obj else np.zeros(3)
        faces = tri[fi]
        used, inv = np.unique(faces, return_inverse=True)
        verts = co[used] - F.REST[j] - at
        out.append((obj.name if len(joints) == 1 else f'{obj.name}_{j}', j, obj.get('game_group', 'body'), obj.get('game_tex', 'cloth'), float(obj.get('game_emissive', 0.0)), at, verts, inv.reshape(-1, 3), col[fi]))
    return out


def blob(verts, faces, cols):
    q = np.round(verts / 1e-4).astype(np.int64)  # weld what is within a tenth of a millimetre
    uniq, first, inv = np.unique(q, axis=0, return_index=True, return_inverse=True)
    v = verts[first]
    f = inv[faces]
    keep = (f[:, 0] != f[:, 1]) & (f[:, 1] != f[:, 2]) & (f[:, 0] != f[:, 2])
    f, cols = f[keep], cols[keep]
    pal, ci = np.unique(np.round(cols, 4), axis=0, return_inverse=True)
    lo, hi = v.min(axis=0), v.max(axis=0)
    span = np.maximum(hi - lo, 1e-6)
    qv = np.round((v - lo) / span * 65535 - 32768).astype(np.int16)
    if len(v) > 65535 or len(f) > 65535 or len(pal) > 255:
        raise ValueError('part too large for the 16-bit form')
    b = bytearray(struct.pack('<HHH6f', len(v), len(f), len(pal), *lo, *hi))
    b += qv.astype('<i2').tobytes() + f.astype('<u2').tobytes() + ci.astype(np.uint8).tobytes() + pal.astype('<f4').tobytes()
    return base64.b64encode(bytes(b)).decode(), len(v), len(f)


def ts_list(x):
    return '[' + ', '.join(f'{float(v):.4g}' for v in x) + ']'


def bake(blend, clips=True):
    bpy.ops.wm.open_mainfile(filepath=blend)
    parts = []
    for obj in bpy.data.objects:
        if obj.type == 'MESH':
            parts += mesh_parts(obj)
    parts.sort(key=lambda p: (p[2] != 'body', p[2], F.ORDER.index(p[1]), p[0]))
    os.makedirs(OUT, exist_ok=True)
    index, packs, tris = [], [], 0
    for name, joint, group, tex, glow, at, verts, faces, cols in parts:
        text, nv, nf = blob(verts, faces, cols)
        tris += nf if group == 'body' else 0
        index.append(f"  {{ id: '{name}', joint: '{joint}', group: '{group}', tex: '{tex}', glow: {glow:g}{', at: ' + ts_list(at) if np.any(at) else ''} }},")
        packs.append(f"  {name}: '{text}',")
    head = '/** Generated by tools/player/bake_player.py from tools/player/build/investigator.blend (docs/PLAYER.md): do not edit by hand. */\n'
    open(os.path.join(OUT, 'playerIndex.ts'), 'w').write(
        head + "\nexport type PlayerJoint = 'body' | 'torso' | 'head' | 'armR' | 'elbowR' | 'handR' | 'armL' | 'elbowL' | 'handL' | 'legR' | 'kneeR' | 'footR' | 'legL' | 'kneeL' | 'footL' | 'skirtR' | 'skirtL';\n"
        "\nexport interface PlayerPart {\n  id: string;\n  joint: PlayerJoint;\n  group: string; // body (always), arm:<weapon>, gun, holstered, flash, flame, prop:<item>\n  tex: 'cloth' | 'wood' | 'flesh';\n  glow: number;\n  at?: readonly [number, number, number]; // where the part's own origin sits in its joint's frame\n}\n"
        "\nexport const PLAYER_PARTS: readonly PlayerPart[] = [\n" + '\n'.join(index) + '\n];\n')
    open(os.path.join(OUT, 'playerPack.ts'), 'w').write(head + '\nexport const PLAYER_PACK: Readonly<Record<string, string>> = {\n' + '\n'.join(packs) + '\n};\n')
    print(f'baked {len(parts)} parts, {tris} body triangles')
    if clips:
        try:
            import clips as C
        except ImportError:
            return
        C.bake(OUT)


if __name__ == '__main__':
    a = sys.argv[1:]
    bake(a[a.index('--blend') + 1] if '--blend' in a else os.path.join(HERE, 'build', 'investigator.blend'), '--no-clips' not in a)
