"""Gathers the facts each model carries (its scene's `seventy` extras) from public/models/*.glb into
src/data/modelManifest.ts, which the game and its tests read (docs/MODELS.md). Runs at the end of
every build; by hand: `python3 tools/blender/manifest.py`."""

import fcntl
import json
import os
import struct

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
MODELS = os.path.join(ROOT, 'public', 'models')
OUT = os.path.join(ROOT, 'src', 'data', 'modelManifest.ts')


def read(path):
    with open(path, 'rb') as f:
        magic, _, _ = struct.unpack('<4sII', f.read(12))
        assert magic == b'glTF', f'{path}: not a GLB'
        n, kind = struct.unpack('<I4s', f.read(8))
        assert kind == b'JSON'
        doc = json.loads(f.read(n))
    facts = json.loads(doc['scenes'][0]['extras']['seventy'])
    names = {a['name'] for a in doc.get('animations', [])}
    missing = set(facts['clips']) - names
    assert not missing, f'{path}: clips not in the file: {sorted(missing)}'
    facts['bytes'] = os.path.getsize(path)
    return facts


def main():
    with open(os.path.join(HERE, '.manifest.lock'), 'w') as lock:
        fcntl.flock(lock, fcntl.LOCK_EX)
        files = sorted(f for f in os.listdir(MODELS) if f.endswith('.glb')) if os.path.isdir(MODELS) else []
        all_facts = {f[:-4]: read(os.path.join(MODELS, f)) for f in files}
        body = ',\n'.join(f'  {k}: {json.dumps(v, separators=(",", ":"))}' for k, v in all_facts.items())
        text = (
            '/** Generated by tools/blender/manifest.py from public/models/*.glb (docs/MODELS.md): do not edit. */\n\n'
            "import type { ModelFacts } from './models';\n\n"
            f'export const MODEL_FACTS: Readonly<Record<string, ModelFacts>> = {{\n{body}{"," if body else ""}\n}};\n'
        )
        with open(OUT, 'w') as f:
            f.write(text)
        print(f'manifest: {len(all_facts)} models')


if __name__ == '__main__':
    main()
