/**
 * Reads Kenney's CC0 animal-horse.glb (node transforms, no skin) and writes src/render/draftHorseData.ts.
 * The chariot body is not in this file. Run: node tools/draft_horse.mjs <animal-horse.glb>
 */
import { readFileSync, writeFileSync } from 'node:fs';

const glb = readFileSync(process.argv[2]);
const jsonLen = glb.readUInt32LE(12);
const json = JSON.parse(glb.subarray(20, 20 + jsonLen).toString());
const bin = glb.subarray(20 + jsonLen + 8);
const round = (n) => Math.round(n * 1e5) / 1e5;

function accessor(index) {
  const a = json.accessors[index];
  const view = json.bufferViews[a.bufferView];
  const start = (view.byteOffset ?? 0) + (a.byteOffset ?? 0);
  const comps = { SCALAR: 1, VEC2: 2, VEC3: 3, VEC4: 4 }[a.type];
  const count = a.count * comps;
  const raw = bin.subarray(start, start + count * ({ 5120: 1, 5121: 1, 5123: 2, 5126: 4 }[a.componentType] ?? 0));
  if (a.componentType === 5126) return Array.from(new Float32Array(raw.buffer, raw.byteOffset, count), round);
  if (a.componentType === 5123) return Array.from(new Uint16Array(raw.buffer, raw.byteOffset, count));
  if (a.componentType === 5121) return Array.from(raw);
  throw new Error(`unexpected component ${a.componentType}`);
}

const nodes = [];
const indexOf = new Map();
function add(i, parent) {
  const n = json.nodes[i];
  const mine = nodes.length;
  indexOf.set(i, mine);
  const mesh = n.mesh == null ? null : json.meshes[n.mesh].primitives[0];
  nodes.push({
    name: n.name,
    parent,
    t: (n.translation ?? [0, 0, 0]).map(round),
    ...(mesh ? { pos: accessor(mesh.attributes.POSITION), nrm: accessor(mesh.attributes.NORMAL), idx: accessor(mesh.indices) } : {}),
  });
  for (const child of n.children ?? []) add(child, mine);
}
for (const root of json.scenes[0].nodes) add(root, -1);

const clips = {};
for (const anim of json.animations) {
  if (anim.name !== 'walk' && anim.name !== 'run') continue;
  clips[anim.name] = {
    duration: round(accessor(anim.samplers[0].input).at(-1)),
    channels: anim.channels.map((ch) => {
      const samp = anim.samplers[ch.sampler];
      return {
        node: json.nodes[ch.target.node].name,
        path: ch.target.path,
        times: accessor(samp.input),
        values: accessor(samp.output),
      };
    }),
  };
}

const out = `/** Kenney Prototype Kit animal-horse (CC0-1.0). Node curves, not a skin. Generated by tools/draft_horse.mjs. */
export const DRAFT_HORSE_JSON = ${JSON.stringify(JSON.stringify({ nodes, clips }))};
`;
writeFileSync(new URL('../src/render/draftHorseData.ts', import.meta.url), out);
console.log(`nodes ${nodes.length}, clips ${Object.keys(clips).join(',')}, bytes ${out.length}`);
