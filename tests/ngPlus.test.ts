/** Finite-resource NG+ acceptance. Uses real health, healing, ammunition, special mechanics and deaths. */
import { writeFileSync } from 'node:fs';
import { describe, expect, it } from 'vitest';
import { JOURNEY_REFERENCE } from '../src/data/ngPlusTuning';
import { ENTITIES } from '../src/data/registry';
import { WEAPON_IDS } from '../src/data/weapons';
import { botFight, type BotFight, type BotStyle } from './botHelpers';

const BOSSES = ENTITIES.filter((e) => e.bossScript || e.bossVariant?.bossScript);
const FRAMES = 60 * 240;
interface Result { id: string; cycle: number; seed: number; build: string; won: boolean; seconds: number; doses: number; damage: number; healed: number; deaths: number; phases: number[] }
const rows: Result[] = [];

const style = (cycle: number, capped = false): BotStyle => ({
  cycle, resources: true, levels: capped ? { vigour: 30, endurance: 30, might: 30 } : { ...JOURNEY_REFERENCE },
  reinforced: 5, reagentMax: 10, skill: 0.9, smart: true, mind: true, start: 10,
});

function measure(cycle: number, capped: boolean): Result[] {
  const measured: Result[] = [];
  for (const e of BOSSES) {
    for (const seed of [77, 211]) {
      const variant = e.bossScript ? undefined : 'boss';
      const r: BotFight = botFight(e.id, FRAMES, variant, { ...style(cycle, capped), seed, start: seed === 77 ? 10 : 13 });
      expect(r.bad, e.id).toEqual([]);
      expect(r.doses, e.id).toBeGreaterThanOrEqual(0);
      expect(r.doses, e.id).toBeLessThanOrEqual(10);
      expect(r.shots, e.id).toBeGreaterThanOrEqual(0);
      expect(r.shots, e.id).toBeLessThanOrEqual(18);
      expect(r.remaining, e.id).toBeGreaterThanOrEqual(0);
      if (r.deaths) expect(r.fell, e.id).toBe(false);
      const row = { id: e.id, cycle, seed, build: capped ? 'cap' : 'reference', won: r.fell, seconds: r.frames / 60, doses: r.doses, damage: r.taken, healed: r.healed, deaths: r.deaths, phases: r.phases };
      rows.push(row);
      measured.push(row);
      if (process.env.NGPLUS_TRACE) console.log(JSON.stringify(row));
    }
  }
  return measured;
}

describe('finite journeys', () => {
  for (const [cycle, capped] of [[1, false], [2, false], [3, false], [7, true]] as const) {
    it(`NG+${cycle}, ${capped ? 'cap' : 'reference'} build`, () => {
      const measured = measure(cycle, capped);
      // A fixed bot is a regression benchmark, not a claim that every player wins every fight.
      // These broad floors protect against a broken roster while allowing a steep optional challenge.
      const floor = { 1: 0.6, 2: 0.45, 3: 0.35, 7: 0.25 }[cycle];
      expect(measured.filter((r) => r.won).length / measured.length).toBeGreaterThanOrEqual(floor);
    }, 240_000);
  }

  it('writes the measured acceptance results when requested', () => {
    if (process.env.NGPLUS_WRITE) {
      const median = (xs: number[]): string => {
        const sorted = [...xs].sort((a, b) => a - b);
        return sorted.length ? sorted[Math.floor(sorted.length / 2)].toFixed(0) : '—';
      };
      const summary = [1, 2, 3, 7].map((cycle) => {
        const at = rows.filter((r) => r.cycle === cycle);
        const wins = at.filter((r) => r.won);
        return `| NG+${cycle} | ${wins.length}/${at.length} | ${median(wins.map((r) => r.seconds))} | ${median(wins.map((r) => r.doses))} |`;
      });
      const cells = BOSSES.map((b) => `| ${b.name} | ${[1, 2, 3, 7].map((cycle) => {
        const wins = rows.filter((r) => r.id === b.id && r.cycle === cycle && r.won);
        return `${wins.length}/2; ${median(wins.map((r) => r.seconds))}`;
      }).join(' | ')} |`);
      writeFileSync('docs/NGPLUS_RESULTS.md', `# Finite-resource journey benchmark\n\nGenerated by NGPLUS_WRITE=1 npm run audit. Two deterministic seeds/starts, skill 0.9, cane +5, gun +5, ten healing doses, real health, finite ammunition, real death; no waived mechanics. NG+1–3 use 18/9/17 attributes; NG+7 uses 30/30/30. The clear synthetic arena uses the authored encounter radius; this is not a collision or human playtest of the actual dungeon.\n\nFailures remain visible. A fixed bot is a regression benchmark, not a success-rate prediction for players or proof that every encounter is fair. Some losses are to unsupported strategies, including petrification/platform navigation, or the four-minute timeout. Successful-run medians exclude deaths and timeouts. Acceptance floors are roster regressions (60%, 45%, 35%, 25%), not individual fight certifications.\n\n| Journey | Wins / runs | Median successful seconds | Median successful healing doses |\n| --- | --- | --- | --- |\n${summary.join('\n')}\n\nCells: wins out of two; median successful seconds (— if neither won).\n\n| Encounter | NG+1 | NG+2 | NG+3 | NG+7, cap build |\n| --- | --- | --- | --- | --- |\n${cells.join('\n')}\n`);
    }
    expect(rows).toHaveLength(BOSSES.length * 8);
  });

  it('supports every weapon and a modest carry with finite resources in the opening NG+ encounter', () => {
    for (const weapon of WEAPON_IDS) {
      const r = botFight('dr_munoz', FRAMES, undefined, { ...style(1), weapon, reinforced: 3, reagentMax: 6, levels: { vigour: 12, endurance: 6, might: 10 } });
      expect(r.bad, weapon).toEqual([]);
      expect(r.fell, weapon).toBe(true);
      expect(r.shots, weapon).toBeLessThanOrEqual(18);
      expect(r.doses, weapon).toBeLessThanOrEqual(6);
    }
  }, 30_000);

  it('keeps every ordinary hostile defeatable at the ceiling with a legal capped build', () => {
    const foes = ENTITIES.filter((e) => !e.bossScript && e.tier !== 'ally');
    const lost: string[] = [];
    for (const e of foes) {
      const r = botFight(e.id, 60 * 90, undefined, { ...style(7, true), sanity: e.hidden?.maxSanity === undefined ? undefined : 0, mind: e.hidden?.maxSanity === undefined });
      expect(r.bad, e.id).toEqual([]);
      if (!r.fell) lost.push(`${e.id}: ${Math.round(r.frames / 60)}s, dealt ${r.dealt}, taken ${r.taken}, doses ${r.doses}, shots ${r.shots}, nearest ${r.nearest.toFixed(1)}`);
    }
    expect(lost).toEqual([]);
  }, 60_000);
});
