/**
 * The colours of each horror's attacks (telegraphs, particles, beams). The blows themselves are
 * unchanged: the same arcs, bolts and rings, in that horror's colours. A fighter with no entry
 * keeps the old shared magenta, green, bone and purple. Data only: no Three.js.
 */

export type Rgb = readonly [number, number, number];

export interface AttackTheme {
  danger: Rgb; // where a blow lands
  line: Rgb; // a bolt or a beam
  ring: Rgb; // a quake's band, and the dust of a burst
  mind: Rgb; // a gaze, a vortex, a summoning
}

const rgb = (hex: number): Rgb => [((hex >> 16) & 255) / 255, ((hex >> 8) & 255) / 255, (hex & 255) / 255];

const th = (danger: number, line: number, ring: number, mind: number): AttackTheme => ({
  danger: rgb(danger), line: rgb(line), ring: rgb(ring), mind: rgb(mind),
});

